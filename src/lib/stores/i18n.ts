const dicts: Record<'uk' | 'en', Dict> = { uk, en };

let current: 'uk' | 'en' = 'en';

export function resolveLang(setting: LangSetting): 'uk' | 'en' {
  if (setting === 'uk' || setting === 'en') return setting;
  const nav = typeof navigator !== 'undefined' ? navigator.language.toLowerCase() : 'en';
  return nav.startsWith('uk') ? 'uk' : 'en';
}

export function setLang(setting: LangSetting): void {
  current = resolveLang(setting);
}

export function getLang(): 'uk' | 'en' {
  return current;
}

/**
 * Labels for the native menu, keyed by the ids Rust builds it from.
 *
 * The submenu titles keep their `menu.` prefix because they are not commands;
 * the items drop it, so the Rust side asks for `save` rather than
 * `menu.save` and one dictionary answers both sides.
 */
export function menuLabels(): Record<string, string> {
  const ids = [
    'newFile',
    'open',
    'openFolder',
    'save',
    'saveAs',
    'closeTab',
    'find',
    'goToHeading',
    'goToLine',
    'toggleSidebar',
    'toggleOutline',
    'foldAll',
    'unfoldAll',
    'formatDocument',
    'zoomIn',
    'zoomOut',
    'zoomReset',
    'exportHtml',
    'print',
    'settings',
    'about'
  ];

  const out: Record<string, string> = {};
  for (const id of ids) out[id] = t(`menu.${id}`);
  for (const part of ['file', 'edit', 'view', 'help']) out[`menu.${part}`] = t(`menu.${part}`);
  return out;
}

/** Translate a key, with optional {placeholder} substitution. */
export function t(key: string, vars?: Record<string, string>): string {
  const dict = dicts[current];
  let out = dict[key] ?? en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) out = out.replace(`{${k}}`, v);
  }
  return out;
}
